 internal static string Format(string text,params object[] args)=>string.Format(Culture,L(text),args);
 internal static string Status(string text){
  if(!English||String.IsNullOrEmpty(text))return text;
  foreach(string prefix in StatusPrefixes){
   if(!text.StartsWith(prefix,StringComparison.Ordinal))continue;
   string rest=text[prefix.Length..];
   return L(prefix)+rest+(prefix=="Ses · %"?"%":"");
  }
  const string waterSuffix=" ml · Gününe küçük bir ara.";
  if(text.EndsWith(waterSuffix,StringComparison.Ordinal))return text[..^waterSuffix.Length]+L(waterSuffix);
  int separator=text.IndexOf(": ",StringComparison.Ordinal);
  if(separator>=0)return text[..(separator+2)]+L(text[(separator+2)..]);
  return L(text);
 }
